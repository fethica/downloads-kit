/**
 * Build identity, the loopback server, storage names, each fixture's expected and
 * computed SHA-256 with its cache proof, and (debug builds only) the scenario switches
 * that drive the fixture server.
 */
@Composable
internal fun DiagnosticsPanel(sample: SampleController, entries: List<DownloadEntry>) {
    val port by sample.port.collectAsState()
    val previousPort by sample.previousPort.collectAsState()
    val generated by sample.generatedSha.collectAsState()
    val verifications by sample.verifications.collectAsState()
    val scenarios by sample.scenarios.collectAsState()
    var requestCounts by remember { mutableStateOf(emptyMap<String, Int>()) }
    LaunchedEffect(Unit) {
        while (true) {
            requestCounts = sample.fixtures.associate { it.name to sample.server.requestCount(it) }
            delay(1_000)
        }
    }

    LazyColumn(
        modifier = Modifier.fillMaxSize(),
        contentPadding = PaddingValues(16.dp),
        verticalArrangement = Arrangement.spacedBy(12.dp),
    ) {
        item {
            Section("Build") {
                Line("Version", "${BuildConfig.VERSION_NAME} (${BuildConfig.VERSION_CODE})")
                Line("Commit", BuildConfig.GIT_COMMIT)
                Line("Package", BuildConfig.APPLICATION_ID)
                Line("Build type", BuildConfig.BUILD_TYPE)
            }
        }
        item {
            Section("Fixture server") {
                Line("Address", if (port > 0) "127.0.0.1:$port" else "not running")
                previousPort?.let {
                    Line(
                        "Endpoint changed",
                        "from 127.0.0.1:$it. Unfinished downloads from the last launch still use it; Retry requests them here.",
                    )
                }
                Line("Source", "self-generated WAV fixtures (FixtureCatalog)")
                sample.fixtures.forEach { Line("Requests, ${it.name}", (requestCounts[it.name] ?: 0).toString()) }
            }
        }
        item {
            Section("Storage") {
                Line("Cache dir", "filesDir/${SampleController.CACHE_DIR}")
                Line("Wi-Fi flag", "${SampleController.SETTINGS_PREFS}.xml, key wifi_only")
                Line("Sample state", "${SampleController.STATE_PREFS}.xml")
                Line("Channel", SampleController.CHANNEL_ID)
                Line("Notification id", SampleController.NOTIFICATION_ID.toString())
                Line("Scheduler", "none")
            }
        }
        items(sample.fixtures, key = { it.name }) { fixture ->
            FixtureProof(
                fixture = fixture,
                state = entries.stateOf(fixture.name),
                generatedSha = generated[fixture.name],
                verification = verifications[fixture.name],
                onVerify = { sample.verify(fixture) },
            )
        }
        if (BuildConfig.DEBUG) {
            item { ScenarioSwitches(sample, scenarios) }
        }
    }
}

@Composable
private fun FixtureProof(
    fixture: WavFixture,
    state: DownloadState,
    generatedSha: String?,
    verification: VerificationLedger.Status<SampleController.Verdict>?,
    onVerify: () -> Unit,
) {
    val pinned = FixtureCatalog.PINNED_SHA256[fixture.name]
    Section(fixture.name) {
        Line("Size", "${fixture.sizeBytes} bytes")
        Line("State", SampleController.stateLabel(state))
        Hash("Expected (pinned)", pinned)
        Hash(
            "Generated on device" + if (generatedSha != null && generatedSha != pinned) ", MISMATCH" else "",
            generatedSha,
        )
        when (verification) {
            null -> Unit
            is VerificationLedger.Status.Running -> Line("Verify", "running")
            is VerificationLedger.Status.Done -> {
                val r = verification.result.result
                Line("Checked key", verification.cacheKey)
                Hash("Read through cache", r.sha256)
                Line("Bytes read", "${r.bytesRead} of ${r.expectedBytes}")
                Line("Cached before read", "${r.cachedBytesBefore} (isCached ${r.fullyCachedBefore})")
                Line("Recorded length", r.recordedLength.toString())
                Line("Upstream opens", r.upstreamOpens.toString())
                r.error?.let { Line("Error", it) }
                Line("Verdict", if (verification.result.matchesFixture) "PASS: cache-only read, SHA-256 matches" else "FAIL")
            }
        }
        OutlinedButton(
            onClick = onVerify,
            enabled = state is DownloadState.Downloaded && verification !is VerificationLedger.Status.Running,
            modifier = Modifier.padding(top = 8.dp),
        ) { Text("Verify") }
    }
}

/** Debug builds only: the switches that make the fixture server misbehave. */
@Composable
private fun ScenarioSwitches(sample: SampleController, scenarios: Map<String, Scenario>) {
    var targetName by rememberSaveable { mutableStateOf<String?>(null) }
    val targets = sample.fixtures.filter { targetName == null || it.name == targetName }
    fun all(predicate: (Scenario) -> Boolean) =
        targets.all { predicate(scenarios[it.name] ?: Scenario.NORMAL) }

    Section("Scenarios (debug only)") {
        Text("Apply to", style = MaterialTheme.typography.labelLarge)
        TargetOption("All fixtures", targetName == null) { targetName = null }
        sample.fixtures.forEach { fixture ->
            TargetOption(fixture.name, targetName == fixture.name) { targetName = fixture.name }
        }
        ScenarioSwitch("Delay first byte (3 s)", all { it.delayFirstByteMs > 0 }) { on ->
            sample.updateScenario(targets) { _, s -> s.copy(delayFirstByteMs = if (on) 3_000L else 0L) }
        }
        ScenarioSwitch("Slow chunks (16 KiB every 250 ms)", all { it.chunkSize > 0 }) { on ->
            sample.updateScenario(targets) { _, s ->
                if (on) s.copy(chunkSize = 16 * 1024, chunkDelayMs = 250L) else s.copy(chunkSize = 0, chunkDelayMs = 0L)
            }
        }
        ScenarioSwitch("Fail with 404", all { it.failWithStatus == 404 }) { on ->
            sample.updateScenario(targets) { _, s -> s.copy(failWithStatus = if (on) 404 else null) }
        }
        ScenarioSwitch("Fail with 500", all { it.failWithStatus == 500 }) { on ->
            sample.updateScenario(targets) { _, s -> s.copy(failWithStatus = if (on) 500 else null) }
        }
        ScenarioSwitch("Cut mid-transfer (after half the file)", all { it.cutAfterBytes != null }) { on ->
            sample.updateScenario(targets) { f, s -> s.copy(cutAfterBytes = if (on) f.sizeBytes / 2L else null) }
        }
        TextButton(onClick = sample::resetScenarios) { Text("Reset all scenarios") }
    }
}

@Composable
private fun TargetOption(label: String, selected: Boolean, onSelect: () -> Unit) {
    Row(
        verticalAlignment = Alignment.CenterVertically,
        modifier = Modifier.fillMaxWidth().selectable(selected = selected, onClick = onSelect, role = Role.RadioButton),
    ) {
        RadioButton(selected = selected, onClick = null)
        Text(label, modifier = Modifier.padding(start = 8.dp))
    }
}

@Composable
private fun ScenarioSwitch(label: String, checked: Boolean, onChange: (Boolean) -> Unit) {
    Row(verticalAlignment = Alignment.CenterVertically, modifier = Modifier.fillMaxWidth()) {
        Text(label, modifier = Modifier.weight(1f))
        Switch(checked = checked, onCheckedChange = onChange)
    }
}

@Composable
private fun Section(title: String, content: @Composable () -> Unit) {
    Card(Modifier.fillMaxWidth()) {
        Column(Modifier.padding(12.dp)) {
            Text(title, style = MaterialTheme.typography.titleSmall, modifier = Modifier.padding(bottom = 4.dp))
            content()
        }
    }
}

@Composable
private fun Line(label: String, value: String) {
    Row(Modifier.fillMaxWidth().padding(vertical = 2.dp)) {
        Text(label, style = MaterialTheme.typography.bodySmall, modifier = Modifier.weight(0.4f))
        Text(value, style = MaterialTheme.typography.bodySmall, modifier = Modifier.weight(0.6f))
    }
}

@Composable
private fun Hash(label: String, value: String?) {
    Column(Modifier.padding(vertical = 2.dp)) {
        Text(label, style = MaterialTheme.typography.bodySmall)
        Text(
            value ?: "-",
            style = MaterialTheme.typography.labelSmall,
            fontFamily = FontFamily.Monospace,
        )
    }
}
