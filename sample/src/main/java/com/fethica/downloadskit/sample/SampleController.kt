package com.fethica.downloadskit.sample

import android.content.Context
import android.net.Uri
import com.fethica.downloadskit.DownloadEntry
import com.fethica.downloadskit.DownloadFailureReason
import com.fethica.downloadskit.DownloadState
import com.fethica.downloadskit.MediaDownloads
import com.fethica.downloadskit.sample.fixtures.FixtureCatalog
import com.fethica.downloadskit.sample.fixtures.FixtureServer
import com.fethica.downloadskit.sample.fixtures.Scenario
import com.fethica.downloadskit.sample.fixtures.WavFixture
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.SupervisorJob
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.flow.update
import kotlinx.coroutines.launch
import kotlinx.coroutines.withContext

/**
 * Everything the sample screen does, in one place: the loopback fixture server, the
 * mapping from fixture to download request, the SHA-256 proof and the scenario switches.
 *
 * The sample keeps its own small state file ([STATE_PREFS]) for the server port and the
 * URL each item was requested with. Both exist for one reason: the Media3 cache key is
 * the request URL, so a relaunch on a different port must still find completed bytes
 * under the URL they were downloaded from.
 */
internal class SampleController(
    context: Context,
    val downloads: MediaDownloads,
) {
    private val prefs = context.applicationContext.getSharedPreferences(STATE_PREFS, Context.MODE_PRIVATE)
    private val scope = CoroutineScope(SupervisorJob() + Dispatchers.Default)

    val server = FixtureServer(FixtureCatalog.all)
    val fixtures: List<WavFixture> = FixtureCatalog.all

    private val _port = MutableStateFlow(-1)
    val port: StateFlow<Int> = _port.asStateFlow()

    private val _scenarios = MutableStateFlow<Map<String, Scenario>>(emptyMap())
    val scenarios: StateFlow<Map<String, Scenario>> = _scenarios.asStateFlow()

    /** SHA-256 computed on this device from freshly generated bytes, by fixture name. */
    private val _generatedSha = MutableStateFlow<Map<String, String>>(emptyMap())
    val generatedSha: StateFlow<Map<String, String>> = _generatedSha.asStateFlow()

    private val _verifications = MutableStateFlow<Map<String, Verification>>(emptyMap())
    val verifications: StateFlow<Map<String, Verification>> = _verifications.asStateFlow()

    sealed interface Verification {
        data object Running : Verification
        data class Done(val result: CacheProof.Result, val matchesFixture: Boolean) : Verification
    }

    fun start() {
        // Binding a loopback socket is quick; the fixture bytes are generated lazily, on
        // the first request or below on a background dispatcher.
        scope.launch(Dispatchers.IO) {
            val bound = server.start(preferredPort = prefs.getInt(KEY_PORT, 0))
            prefs.edit().putInt(KEY_PORT, bound).apply()
            _port.value = bound
            SampleLog.event("server", "listening", "host=127.0.0.1:$bound")
        }
        scope.launch {
            _generatedSha.value = fixtures.associate { it.name to it.sha256 }
        }
        downloads.addListener(object : MediaDownloads.Listener {
            override fun onStarted(id: String, group: String?) = SampleLog.event(id, "started", "group=$group")
            override fun onCompleted(id: String, bytes: Long, seconds: Long) =
                SampleLog.event(id, "completed", "bytes=$bytes seconds=$seconds")
            override fun onFailed(id: String, reason: DownloadFailureReason) =
                SampleLog.event(id, "failed", "reason=${reason.key}")
            override fun onRemoved(id: String, bytes: Long) = SampleLog.event(id, "removed", "bytes=$bytes")
            override fun onClearedAll(count: Int, bytes: Long) =
                SampleLog.event("*", "cleared_all", "count=$count bytes=$bytes")
        })
        scope.launch { logStateTransitions() }
    }

    /** One line per state change of an item (and per 25 % of progress), not per poll. */
    private suspend fun logStateTransitions() {
        val last = HashMap<String, String>()
        downloads.all().collect { entries ->
            val seen = HashSet<String>()
            for (entry in entries) {
                seen += entry.id
                val label = stateLabel(entry.state, bucketed = true)
                if (last[entry.id] != label) {
                    last[entry.id] = label
                    SampleLog.event(entry.id, label, "bytes=${entry.bytes}")
                }
            }
            (last.keys - seen).forEach {
                last.remove(it)
                SampleLog.event(it, "not_downloaded")
            }
        }
    }

    // ---------------------------------------------------------------- items

    fun fixture(id: String): WavFixture? = FixtureCatalog.byName(id)

    fun groupOf(fixture: WavFixture): String = if (fixture == FixtureCatalog.large) GROUP_LONG else GROUP_SHORT

    fun groupTitle(group: String): String = when (group) {
        GROUP_SHORT -> "Short fixtures"
        GROUP_LONG -> "Long fixture"
        else -> group
    }

    /** Files the fixture with the server's current URL, and remembers that URL. */
    fun start(fixture: WavFixture) {
        if (!server.isRunning) {
            SampleLog.event(fixture.name, "request_skipped", "reason=server_not_running")
            return
        }
        val url = server.urlFor(fixture)
        prefs.edit().putString(KEY_URL_PREFIX + fixture.name, url).apply()
        downloads.request(
            id = fixture.name,
            uri = Uri.parse(url),
            title = fixture.name,
            subtitle = "${fixture.sizeBytes} bytes, ${fixture.toneHz} Hz tone",
            group = groupOf(fixture),
            mimeType = MIME_WAV,
        )
        SampleLog.event(fixture.name, "requested", "host=127.0.0.1:${server.port} path=${fixture.path}")
    }

    /**
     * The library has no retry of its own (a row carries no URL), so a retry is the host
     * asking again: Media3 merges the request into the failed download and queues it,
     * keeping whatever bytes already landed.
     */
    fun retry(fixture: WavFixture) {
        SampleLog.event(fixture.name, "retry_requested")
        start(fixture)
    }

    fun remove(id: String) {
        SampleLog.event(id, "remove_requested")
        downloads.remove(id)
    }

    fun removeGroup(group: String) {
        SampleLog.event("group:$group", "remove_group_requested")
        downloads.removeGroup(group)
    }

    fun clearAll() {
        SampleLog.event("*", "clear_all_requested")
        downloads.clearAll()
    }

    fun setWifiOnly(enabled: Boolean) {
        SampleLog.event("*", "wifi_only", "enabled=$enabled")
        downloads.wifiOnly.value = enabled
    }

    // ---------------------------------------------------------------- proof

    /** The cache key of a fixture: the URL it was requested with. */
    fun cacheKey(fixture: WavFixture): String? =
        prefs.getString(KEY_URL_PREFIX + fixture.name, null)
            ?: server.takeIf { it.isRunning }?.urlFor(fixture)

    fun verify(fixture: WavFixture) {
        val key = cacheKey(fixture) ?: return
        _verifications.update { it + (fixture.name to Verification.Running) }
        scope.launch {
            val result = withContext(Dispatchers.IO) {
                CacheProof.verify(downloads, key, fixture.sizeBytes.toLong())
            }
            val matches = result.servedFromCacheOnly && result.sha256 == fixture.sha256
            _verifications.update { it + (fixture.name to Verification.Done(result, matches)) }
            SampleLog.event(
                fixture.name,
                if (matches) "verify_pass" else "verify_fail",
                "bytes=${result.bytesRead} cached=${result.cachedBytesBefore} upstream_opens=${result.upstreamOpens} " +
                    "sha_match=${result.sha256 == fixture.sha256}" + (result.error?.let { " error=$it" } ?: ""),
            )
        }
    }

    // ---------------------------------------------------------------- scenarios

    fun updateScenario(targets: List<WavFixture>, change: (WavFixture, Scenario) -> Scenario) {
        if (!BuildConfig.DEBUG) return
        targets.forEach { fixture -> server.updateScenario(fixture) { change(fixture, it) } }
        publishScenarios()
        targets.forEach { SampleLog.event(it.name, "scenario", describe(server.scenario(it))) }
    }

    fun resetScenarios() {
        if (!BuildConfig.DEBUG) return
        server.resetAll()
        publishScenarios()
        SampleLog.event("*", "scenario", "reset")
    }

    private fun publishScenarios() {
        _scenarios.value = fixtures.associate { it.name to server.scenario(it) }
    }

    companion object {
        /** The sample's own storage names, passed to the library explicitly. */
        const val CACHE_DIR = "sample_downloads"
        const val SETTINGS_PREFS = "sample_downloads"
        const val STATE_PREFS = "sample_fixture_state"
        const val CHANNEL_ID = "sample_downloads"
        const val NOTIFICATION_ID = 4210

        const val GROUP_SHORT = "short"
        const val GROUP_LONG = "long"

        private const val KEY_PORT = "server_port"
        private const val KEY_URL_PREFIX = "url_"
        private const val MIME_WAV = "audio/wav"

        fun describe(scenario: Scenario): String = if (scenario.isDefault) {
            "normal"
        } else {
            buildList {
                if (scenario.delayFirstByteMs > 0) add("delay_first_byte_ms=${scenario.delayFirstByteMs}")
                if (scenario.chunkSize > 0) add("chunk=${scenario.chunkSize}/${scenario.chunkDelayMs}ms")
                scenario.failWithStatus?.let { add("status=$it") }
                scenario.cutAfterBytes?.let { add("cut_after=$it") }
            }.joinToString(" ")
        }

        fun stateLabel(state: DownloadState, bucketed: Boolean = false): String = when (state) {
            DownloadState.NotDownloaded -> "not_downloaded"
            DownloadState.Queued -> "queued"
            is DownloadState.Downloading -> when {
                state.progress < 0f -> "downloading"
                bucketed -> "downloading_${(state.progress * 4).toInt().coerceIn(0, 3) * 25}pct"
                else -> "downloading_${(state.progress * 100).toInt()}pct"
            }
            is DownloadState.Downloaded -> "downloaded"
            is DownloadState.Failed -> "failed_${state.reason.key}"
            DownloadState.Removing -> "removing"
        }
    }
}

internal fun List<DownloadEntry>.stateOf(id: String): DownloadState =
    firstOrNull { it.id == id }?.state ?: DownloadState.NotDownloaded
