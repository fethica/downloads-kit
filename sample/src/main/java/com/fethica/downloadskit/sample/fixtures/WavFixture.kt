package com.fethica.downloadskit.sample.fixtures

import java.security.MessageDigest

/**
 * One self-generated audio file: a valid WAV (44-byte PCM header, 16-bit mono, 8 kHz)
 * holding a short sine tone followed by silence, padded with silence to exactly
 * [sizeBytes].
 *
 * Every byte is a pure function of the constructor arguments. The sine goes through
 * [StrictMath], whose results are specified bit for bit (fdlibm) on every JVM and on
 * Android, and the dither comes from a fixed xorshift generator seeded with [seed], so
 * two generations, on a laptop or on a phone, produce the same bytes and the same
 * SHA-256.
 *
 * @param name a stable, URL-safe name; also the file name in [path].
 * @param seed seeds the dither on the tone; changing it changes the bytes.
 * @param sizeBytes the whole file, header included. Must be even and larger than the header.
 * @param toneHz the frequency of the tone.
 * @param toneMillis how long the tone lasts before the silence.
 */
public class WavFixture(
    public val name: String,
    public val seed: Long,
    public val sizeBytes: Int,
    public val toneHz: Int,
    public val toneMillis: Int,
) {
    init {
        require(name.matches(Regex("[a-z0-9-]+"))) { "name must be URL-safe: $name" }
        require(sizeBytes > HEADER_BYTES && sizeBytes % 2 == 0) { "sizeBytes must be even and > $HEADER_BYTES" }
        require(toneHz in 1 until SAMPLE_RATE / 2) { "toneHz must be below Nyquist" }
        require(toneMillis >= 0)
    }

    /** Where the loopback server serves it. Stable: it carries no port and no query. */
    public val path: String get() = "/fixtures/$name.wav"

    /** The generated file. Built once per instance; callers get their own copy. */
    public fun bytes(): ByteArray = cached.copyOf()

    /** Read-only view for the server, which must not copy a megabyte per request. */
    internal val cached: ByteArray by lazy { generate() }

    /** Lower-case hex SHA-256 of [bytes], computed from the generated bytes. */
    public val sha256: String by lazy { sha256Hex(cached) }

    private fun generate(): ByteArray {
        val out = ByteArray(sizeBytes)
        val dataBytes = sizeBytes - HEADER_BYTES
        writeHeader(out, dataBytes)
        val samples = dataBytes / 2
        val toneSamples = minOf(samples, (SAMPLE_RATE.toLong() * toneMillis / 1000).toInt())
        var state = if (seed == 0L) DEFAULT_STATE else seed
        for (n in 0 until toneSamples) {
            // xorshift64: fixed, documented, no platform Random involved.
            state = state xor (state shl 13)
            state = state xor (state ushr 7)
            state = state xor (state shl 17)
            val dither = (state ushr 62).toInt() - 1 // -1, 0, 1 or 2
            val phase = 2.0 * StrictMath.PI * toneHz * n / SAMPLE_RATE
            val value = StrictMath.round(StrictMath.sin(phase) * AMPLITUDE).toInt() + dither
            val sample = value.coerceIn(Short.MIN_VALUE.toInt(), Short.MAX_VALUE.toInt())
            val at = HEADER_BYTES + n * 2
            out[at] = (sample and 0xFF).toByte()
            out[at + 1] = ((sample shr 8) and 0xFF).toByte()
        }
        // The rest of the data chunk is already zero: silence.
        return out
    }

    override fun toString(): String = "WavFixture($name, $sizeBytes bytes)"

    public companion object {
        public const val HEADER_BYTES: Int = 44
        public const val SAMPLE_RATE: Int = 8_000
        public const val BITS_PER_SAMPLE: Int = 16
        public const val CHANNELS: Int = 1

        /** About -18 dBFS: quiet if anyone ever plays it. */
        private const val AMPLITUDE = 4_000.0
        private const val DEFAULT_STATE = 0x2545F4914F6CDD1DL

        private fun writeHeader(out: ByteArray, dataBytes: Int) {
            val byteRate = SAMPLE_RATE * CHANNELS * BITS_PER_SAMPLE / 8
            val blockAlign = CHANNELS * BITS_PER_SAMPLE / 8
            ascii(out, 0, "RIFF")
            le32(out, 4, 36 + dataBytes)
            ascii(out, 8, "WAVE")
            ascii(out, 12, "fmt ")
            le32(out, 16, 16) // PCM fmt chunk size
            le16(out, 20, 1) // audio format: PCM
            le16(out, 22, CHANNELS)
            le32(out, 24, SAMPLE_RATE)
            le32(out, 28, byteRate)
            le16(out, 32, blockAlign)
            le16(out, 34, BITS_PER_SAMPLE)
            ascii(out, 36, "data")
            le32(out, 40, dataBytes)
        }

        private fun ascii(out: ByteArray, at: Int, text: String) {
            for (i in text.indices) out[at + i] = text[i].code.toByte()
        }

        private fun le16(out: ByteArray, at: Int, value: Int) {
            out[at] = (value and 0xFF).toByte()
            out[at + 1] = ((value shr 8) and 0xFF).toByte()
        }

        private fun le32(out: ByteArray, at: Int, value: Int) {
            for (i in 0 until 4) out[at + i] = ((value shr (8 * i)) and 0xFF).toByte()
        }
    }
}

/** Lower-case hex SHA-256 of [bytes]. */
public fun sha256Hex(bytes: ByteArray): String = sha256Hex(bytes, 0, bytes.size)

/** Lower-case hex SHA-256 of a slice of [bytes]. */
public fun sha256Hex(bytes: ByteArray, offset: Int, length: Int): String {
    val digest = MessageDigest.getInstance("SHA-256")
    digest.update(bytes, offset, length)
    return digest.digest().joinToString("") { "%02x".format(it) }
}
